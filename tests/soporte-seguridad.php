<?php

declare(strict_types=1);

// Soporte para probar controladores sin el firewall: la autenticación, los permisos y el CSRF se
// prueban a través del kernel en tests/seguridad-http.php.

use App\Administracion\SesionAdministrativa;
use App\Seguridad\AuditoriaAccesos;
use App\Seguridad\TokenCsrf;
use App\Seguridad\UsuarioSesion;
use Doctrine\DBAL\Connection;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Session\Session;
use Symfony\Component\HttpFoundation\Session\Storage\MockArraySessionStorage;
use Symfony\Component\Security\Core\Authentication\Token\Storage\TokenStorage;
use Symfony\Component\Security\Core\Authentication\Token\UsernamePasswordToken;
use Symfony\Component\Security\Csrf\CsrfTokenManager;
use Symfony\Component\Security\Csrf\TokenStorage\SessionTokenStorage;

spl_autoload_register(static function (string $clase): void {
    $archivo = __DIR__.'/../src/'.str_replace('\\', '/', substr($clase, 4)).'.php';
    if (str_starts_with($clase, 'App\\') && is_file($archivo)) {
        require $archivo;
    }
});

function sesionDePrueba(?UsuarioSesion $usuario): SesionAdministrativa
{
    $tokens = new TokenStorage();
    if ($usuario !== null) {
        $tokens->setToken(new UsernamePasswordToken($usuario, 'administracion', $usuario->getRoles()));
    }
    $peticion = new Request();
    $peticion->setSession(new Session(new MockArraySessionStorage()));
    $pila = new RequestStack();
    $pila->push($peticion);

    return new SesionAdministrativa($tokens, new TokenCsrf(new CsrfTokenManager(null, new SessionTokenStorage($pila))));
}

function administradoraDePrueba(string $id = '1'): UsuarioSesion
{
    return new UsuarioSesion($id, 'admin@example.test', true, null, 'hash');
}

function auditoriaDePrueba(Connection $conexion): AuditoriaAccesos
{
    $conexion->executeStatement(<<<'SQL'
        CREATE TABLE IF NOT EXISTS eventos_acceso (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tipo VARCHAR(30) NOT NULL,
            usuario_id BIGINT, autor_id BIGINT, ip INET, creado_en TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp()
        )
        SQL);
    $conexion->executeStatement('CREATE TABLE IF NOT EXISTS intentos_acceso_admin (clave CHAR(64) PRIMARY KEY, intentos INT NOT NULL, vence_en TIMESTAMPTZ NOT NULL, bloqueado_hasta TIMESTAMPTZ)');

    return new AuditoriaAccesos($conexion, new RequestStack());
}
