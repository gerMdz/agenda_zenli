<?php

declare(strict_types=1);

use App\Administracion\UsuariosAdministrativos;
use App\Repository\UsuariosAdministrativosRepository;
use Doctrine\DBAL\DriverManager;
use Doctrine\DBAL\Exception\UniqueConstraintViolationException;
use Doctrine\ORM\EntityManager;
use Doctrine\ORM\ORMSetup;

require getenv('ZENLI_TEST_AUTOLOAD') ?: __DIR__.'/../vendor/autoload.php';
spl_autoload_register(static function (string $clase): void {
    if (str_starts_with($clase, 'App\\')) {
        require __DIR__.'/../src/'.str_replace('\\', '/', substr($clase, 4)).'.php';
    }
}, true, true);

$conexion = DriverManager::getConnection(['driver' => 'pdo_pgsql', 'host' => $argv[1], 'port' => $argv[2] ?? 5432, 'user' => 'postgres', 'dbname' => 'postgres']);
$conexion->executeStatement("CREATE TABLE usuarios (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(180) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, roles JSONB NOT NULL DEFAULT '[]', activo BOOLEAN NOT NULL DEFAULT TRUE)");
$conexion->executeStatement('CREATE TABLE profesionales (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id BIGINT UNIQUE REFERENCES usuarios(id), nombre VARCHAR(120) NOT NULL, activa BOOLEAN NOT NULL DEFAULT TRUE)');
$configuracion = ORMSetup::createAttributeMetadataConfiguration([__DIR__.'/../src/Entity'], true);
$configuracion->enableNativeLazyObjects(true);
$em = new EntityManager($conexion, $configuracion);
require __DIR__.'/soporte-seguridad.php';
$auditoria = auditoriaDePrueba($conexion);
$usuarios = new UsuariosAdministrativos(new UsuariosAdministrativosRepository($em, $auditoria), new App\Seguridad\LimiteIngresos($conexion), $auditoria);
$verificar = static function (bool $condicion, string $mensaje): void {
    if (!$condicion) throw new RuntimeException($mensaje);
};
$usuarios->crear(' ADMIN@example.com ', 'clave de prueba segura');
$usuarios->crear('otro@example.com', 'otra clave de prueba');
$hash = $conexion->fetchOne("SELECT password_hash FROM usuarios WHERE email = 'admin@example.com'");
$verificar(password_verify('clave de prueba segura', $hash), 'Debe guardar una contraseña segura.');
$conexion->executeStatement("INSERT INTO usuarios (id, email, password_hash, roles) VALUES (100, 'prof@example.com', 'hash', '[]')");
$conexion->executeStatement("INSERT INTO profesionales (usuario_id, nombre) VALUES (1, 'Profesional')");
$lista = $usuarios->listar();
$verificar(count($lista) === 2 && $lista[0]['id'] === '1' && $lista[0]['profesional'] === 'Profesional', 'Listado incorrecto.');
$huella = hash('sha256', $hash);
$verificar(!$usuarios->actualizar('1', false, '', '1', $huella), 'No debe permitir autodesactivarse.');
$verificar(!$usuarios->actualizar('100', false, '', '1', $huella), 'No debe modificar usuarios sin rol.');
$verificar(!$usuarios->actualizar('2', false, '', '1', 'incorrecta'), 'Debe rechazar credenciales vencidas.');
$verificar($usuarios->actualizar('2', false, '', '1', $huella), 'Debe desactivar otra cuenta.');
$verificar(!$usuarios->actualizar('1', false, '', '2', hash('sha256', $conexion->fetchOne('SELECT password_hash FROM usuarios WHERE id = 2'))), 'Un autor desactivado no puede modificar cuentas.');
$conexion->executeStatement("UPDATE usuarios SET password_hash = 'cambio externo' WHERE id = 1");
$verificar(!$usuarios->actualizar('2', true, '', '1', $huella), 'Debe verificar la credencial actual, no una entidad cacheada.');
try {
    $usuarios->crear('admin@example.com', 'clave de prueba segura');
    throw new RuntimeException('Debe rechazar correos duplicados.');
} catch (UniqueConstraintViolationException) {
}
fwrite(STDOUT, "ABM administrativo ORM verificado.\n");